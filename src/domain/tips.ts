/** Yerel takvime göre gün numarası; saat ve yaz saati farkı sonucu değiştirmez. */
function dayNumber(now: number) {
  const d = new Date(now);
  return Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86_400_000);
}

/**
 * Günün cümlesi: bir gün ev, bir gün spor. Her gün değişir, 200 günde bir hepsi bir kez gelir.
 * 37 ile 100 aralarında asal olduğu için sıra karışık görünür ama hiçbiri atlanmaz.
 */
export function tipOfDay(now = Date.now()) {
  const n = dayNumber(now);
  const half = Math.floor(n / 2);
  const home = n % 2 === 0;
  const list = home ? HOME_TIPS : MOVE_TIPS;
  return { emoji: home ? '🏡' : '🚶', text: list[(half * 37) % list.length] };
}
